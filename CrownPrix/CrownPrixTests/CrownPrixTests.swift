import XCTest
import CoreGraphics
@testable import CrownPrix_Watch_App

final class CrownPrixTests: XCTestCase {
    func testResourcesAccessible() {
        let url = BundleHelper.svgURL(name: "RaceCircuitMonaco", bundle: Bundle.main)
        XCTAssertNotNil(url, "Monaco SVG not found via BundleHelper")
    }

    // MARK: - CollisionSystem.segmentsIntersect

    func testSegmentsIntersectCrossing() {
        let a = CGPoint(x: 0, y: 0)
        let b = CGPoint(x: 10, y: 10)
        let c = CGPoint(x: 0, y: 10)
        let d = CGPoint(x: 10, y: 0)
        XCTAssertTrue(CollisionSystem.segmentsIntersect(a, b, c, d))
    }

    func testSegmentsIntersectParallelNoHit() {
        let a = CGPoint(x: 0, y: 0)
        let b = CGPoint(x: 10, y: 0)
        let c = CGPoint(x: 0, y: 5)
        let d = CGPoint(x: 10, y: 5)
        XCTAssertFalse(CollisionSystem.segmentsIntersect(a, b, c, d))
    }

    func testSegmentsIntersectCollinearNoHit() {
        // Collinear overlapping segments treated as non-intersecting (cross == 0).
        let a = CGPoint(x: 0, y: 0)
        let b = CGPoint(x: 10, y: 0)
        let c = CGPoint(x: 5, y: 0)
        let d = CGPoint(x: 15, y: 0)
        XCTAssertFalse(CollisionSystem.segmentsIntersect(a, b, c, d))
    }

    func testSegmentsIntersectDisjoint() {
        let a = CGPoint(x: 0, y: 0)
        let b = CGPoint(x: 2, y: 2)
        let c = CGPoint(x: 10, y: 10)
        let d = CGPoint(x: 20, y: 10)
        XCTAssertFalse(CollisionSystem.segmentsIntersect(a, b, c, d))
    }

    func testSegmentsIntersectTunneling() {
        // Very long trajectory crossing a short barrier — swept test catches it.
        let a = CGPoint(x: -1000, y: 5)
        let b = CGPoint(x: 1000, y: 5)
        let c = CGPoint(x: 0, y: 0)
        let d = CGPoint(x: 0, y: 10)
        XCTAssertTrue(CollisionSystem.segmentsIntersect(a, b, c, d))
    }

    func testSegmentsIntersectBarrierEndpointGrazeIgnored() {
        // Trajectory ending exactly AT a barrier endpoint should NOT trigger —
        // strict interior on the barrier parameter u protects apex-on-centerline
        // barriers from false positives when cars pass through apex normally.
        let trajectory0 = CGPoint(x: 0, y: 0)
        let trajectory1 = CGPoint(x: 10, y: 0)
        // Barrier endpoint B1 exactly at trajectory end (10, 0)
        let barrier0 = CGPoint(x: 10, y: 5)
        let barrier1 = CGPoint(x: 10, y: 0)
        XCTAssertFalse(CollisionSystem.segmentsIntersect(trajectory0, trajectory1, barrier0, barrier1),
                       "Touching a barrier endpoint should not trigger collision")
    }

    // MARK: - TrackData innerBarriers

    func testMonacoInnerBarriersDecoded() throws {
        let data = try TrackLoader.loadTrackData(trackId: "monaco")
        XCTAssertFalse(data.innerBarriers.isEmpty, "Monaco should have innerBarriers authored")
        // Infield medial-axis barrier down the hairpin throat: placed only where
        // the midpoint between opposite arms lands in the black infield (>= road
        // half-width + 2 off the nearest centerline), leaving an apex gap (±4
        // indices) so the racing line rounds the apex unobstructed. Generated by
        // scripts/validate_barrier.py --regen; verified shortcut-free by
        // scripts/find_shortcuts.py.
        XCTAssertEqual(data.innerBarriers.count, 7)
    }

    func testVilleneuveInnerBarriersDecoded() throws {
        let data = try TrackLoader.loadTrackData(trackId: "gillesvilleneuve")
        XCTAssertFalse(data.innerBarriers.isEmpty, "Canada hairpin should have innerBarriers authored")
        // Infield medial-axis barrier with an apex gap (±6 indices); same
        // black-infield placement rule as Monaco.
        XCTAssertEqual(data.innerBarriers.count, 10)
    }

    func testOtherTracksHaveNoBarriers() throws {
        // Default behavior: tracks without innerBarriers JSON key get empty array.
        let suzuka = try TrackLoader.loadTrackData(trackId: "suzuka")
        XCTAssertTrue(suzuka.innerBarriers.isEmpty)
    }
}
